def test_process_py_on_pr161(tmp_path, pr161_files):
    """Run process.py against the original PR #161 files.

    Expected failures (per spec):
    - Both: .md references external files but no .zip
    - Both: previous version included .zip but this submission does not
    - Both: final spec already exists (title should use errata language)
    - Both: references check fails (openid.net/wg/ekyc-ida/references/ returns 404)
    - Both: missing ABSTRACT (xml2rfc format gap)
    """
    # Seed CSV with the final specs (so "final already exists" check fires)
    # but without the draft filenames themselves (so duplicate check passes).
    csv_content = (
        "Filename,Date,Size\n"
        "openid-connect-4-identity-assurance-1_0-final.html,2025-06-01,300K\n"
        "openid-connect-4-identity-assurance-1_0-16.html,2025-03-01,280K\n"
        "openid-connect-4-identity-assurance-1_0-16.zip,2025-03-01,500K\n"
        "openid-ida-verified-claims-1_0-final.html,2025-06-01,150K\n"
        "openid-ida-verified-claims-1_0-02.html,2025-01-15,140K\n"
        "openid-ida-verified-claims-1_0-02.zip,2025-01-15,300K\n"
    )
    repo_path, scripts_path = create_test_repo(
        tmp_path, pr161_files, spec_list_csv_content=csv_content,
    )

    # Fixture specs are published 2026-03-26 — pin "today" within the 10-day
    # window so the date check doesn't fail as wall-clock time advances.
    result = run_python_script(
        "process.py", repo_path, scripts_path,
        env_overrides={"OVERRIDE_TODAY": "2026-03-30"},
    )

    assert result.returncode == 1, (
        f"Expected exit 1 but got {result.returncode}.\n"
        f"STDOUT:\n{result.stdout}\nSTDERR:\n{result.stderr}"
    )

    clean = re.sub(r'\x1b\[[0-9;]*m', '', result.stdout)

    # Extract all FAIL lines
    fail_lines = [line.strip() for line in clean.splitlines() if line.strip().startswith("FAIL:")]

    # Expected failures
    expected_fails = [
        "references external files",                    # both: .md has includes, no .zip
        "Previous version",                             # both: prev version had .zip
        "Final spec already exists",                    # both: should use errata title
        "Problem with References",                      # both: 404 on wg references URL
        "Missing sections: ABSTRACT",                   # both: xml2rfc format gap
        "did not pass all checks",                      # both: summary line
    ]

    # Check every FAIL line matches at least one expected pattern
    unexpected = []
    for fail in fail_lines:
        if not any(exp in fail for exp in expected_fails):
            unexpected.append(fail)

    assert not unexpected, (
        f"Unexpected failures found:\n"
        + "\n".join(f"  {f}" for f in unexpected)
        + f"\n\nAll FAIL lines:\n"
        + "\n".join(f"  {f}" for f in fail_lines)
    )

    # Verify key expected failures are present
    assert any("references external files" in f for f in fail_lines)
    assert any("Previous version" in f for f in fail_lines)
    assert any("Final spec already exists" in f for f in fail_lines)
    assert any("Missing sections: ABSTRACT" in f for f in fail_lines)


