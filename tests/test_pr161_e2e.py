class TestIDASpec:
    """Tests for openid-connect-4-identity-assurance-1_0-17.html."""

    @pytest.fixture(autouse=True)
    def setup(self, pr161_files):
        self.content = pr161_files[
            "ekyc-ida/openid-connect-4-identity-assurance-1_0-17.html"
        ].decode("utf-8")
        self.filename = "openid-connect-4-identity-assurance-1_0-17.html"

    def test_filename_state_is_draft(self):
        result = spec_validator.filename_state(self.filename)
        assert result["state"] == "DRAFT"

    def test_content_state_is_draft(self):
        result = spec_validator.content_state(self.content)
        assert result["state"] == "DRAFT"

