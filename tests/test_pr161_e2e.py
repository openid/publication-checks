def _load_pr_files():
    """Load actual file contents from the PR branch in the publication repo."""
    files = {}
    for path in _PR_FILES:
        result = subprocess.run(
            ["git", "show", f"{_PR_BRANCH}:{path}"],
            cwd=_PUBLICATION_REPO,
            capture_output=True,
        )
        if result.returncode != 0:
            pytest.skip(f"Could not load {path} from {_PR_BRANCH}")
        files[path] = result.stdout  # bytes, since HTML may have encoding issues
    return files


@pytest.fixture(scope="module")
def pr161_files():
    """Load PR #161 files once for all tests in this module."""
    return _load_pr_files()


