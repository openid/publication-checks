"""
Tests using real files from PR #161 (openid/publication) as originally submitted.

PR #161 adds two specs in ekyc-ida/:
- openid-connect-4-identity-assurance-1_0-17.html (Draft 17 - no errata language)
- openid-ida-verified-claims-1_0-03.html (Draft 03 - no errata language)

Both are generated by xml2rfc. A final already exists for both specs,
so these should have been titled as draft errata but weren't.
Copies of the original PR files are stored in tests/fixtures/.
"""
from __future__ import annotations

